/**
 * Bundles canvas CSS into a generated TS module for standalone exports.
 * Run: node migration/bundle-canvas-css.mjs (also via npm pretest/prebuild).
 * Why generated instead of ?raw imports: deterministic in vitest, vite
 * build AND plain node — snapshot HTML must inline the exact bytes.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const tokens = read('assets/tokens.css');
const fonts = read('src/assets/fonts.css');
const core = read('css/core.css');
const phosphor = read('css/phosphor.css');
const themes = {};
for (const f of readdirSync(join(root, 'themes'))) {
  if (!f.endsWith('.css')) continue;
  themes[f.replace(/\.css$/, '')] = read(`themes/${f}`);
}

// Compact role map for editor preview chips. The editor must not pull the
// full CSS bundle (tokens/fonts/core/phosphor) just to paint a swatch, so
// this emits only the handful of variables a preview needs.
const PREVIEW_ROLES = [
  'bg-deep',
  'panel',
  'text-primary',
  'text-dim',
  'phos-green',
  'amber',
  'cyan-dim',
  'alert-red',
  'canvas-texture',
  'canvas-texture-size',
  // typography is part of a theme's identity — the picker previews it
  'font-display',
  'font-body',
  'font-data',
  'font-hand',
];
const themeVars = {};
for (const [key, css] of Object.entries(themes)) {
  const row = {};
  for (const role of PREVIEW_ROLES) {
    const m = css.match(new RegExp(`--${role}\\s*:\\s*([^;]+);`));
    if (m) row[role] = m[1].trim();
  }
  themeVars[key] = row;
}

const str = (s) => JSON.stringify(s);
const out =
  `/* GENERATED by migration/bundle-canvas-css.mjs — do not hand-edit. */\n` +
  `export const TOKENS_CSS = ${str(tokens)};\n` +
  `export const FONTS_CSS = ${str(fonts)};\n` +
  `export const CORE_CSS = ${str(core)};\n` +
  `export const PHOSPHOR_CSS = ${str(phosphor)};\n` +
  `export const THEME_CSS: Record<string, string> = ${str(themes)};\n`;
writeFileSync(join(root, 'src/export/canvasCss.generated.ts'), out);

const previewOut =
  `/* GENERATED by migration/bundle-canvas-css.mjs — do not hand-edit. */\n` +
  `/** Per-theme role values for editor preview chips (small subset). */\n` +
  `export const THEME_VARS: Record<string, Record<string, string>> = ${str(themeVars)};\n`;
writeFileSync(join(root, 'src/editor/themeVars.generated.ts'), previewOut);

const keys = Object.keys(themes);
console.log(`bundled ${keys.length} themes (${keys.join(' ')}) + tokens/fonts/core/phosphor`);
console.log(`preview vars → src/editor/themeVars.generated.ts (${keys.length} themes)`);
